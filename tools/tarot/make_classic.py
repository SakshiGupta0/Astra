#!/usr/bin/env python3
"""The classic tarot for ASTRA: Pamela Colman Smith's 1909 cards (public domain), plus ASTRA's own card back.

  python3 tools/tarot/make_classic.py <dir with maj00.jpg ... pentacles14.jpg>

Writes:
  app/src/main/res/drawable-nodpi/tarot_<id>.webp   the 78 cards, 600 px wide
  app/src/main/res/drawable/tarot_back.xml          ASTRA yantra card back (vector)
  app/src/main/java/app/astra/ui/tarot/TarotArt.kt   card id -> drawable
  build/tarot/back.svg                              preview of the back
The scans come from Wikimedia Commons (see .github/workflows/fetch-tarot.yml and the tarot-1909 branch manifest).
"""
import math, os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
IDS = [f"maj{i:02d}" for i in range(22)] + [f"{s}{n:02d}" for s in ("wands", "cups", "swords", "pentacles") for n in range(1, 15)]
W, H = 115, 200  # card back viewport, same proportions as the scans (960 x 1670)
GOLD, OLD, LAV, MOON, BACK, DEEP = "#F7D794", "#C9A45C", "#A78BFA", "#F5F3FF", "#1B1446", "#100C33"


def f(x):
    s = f"{x:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


paths = []  # (d, stroke, width, fill, stroke_alpha, fill_alpha)


def P(d, stroke=GOLD, w=0.6, fill=None, sa=1.0, fa=1.0): paths.append((d, stroke, w, fill, sa, fa))
def circle(cx, cy, r, **k): P(f"M{f(cx - r)},{f(cy)}a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0Z", **k)
def poly(pts, **k): P("M" + "L".join(f"{f(x)},{f(y)}" for x, y in pts) + "Z", **k)
def star(cx, cy, ro, ri, n=4, rot=-90, **k):
    poly([(cx + (ro if i % 2 == 0 else ri) * math.cos(math.radians(rot + i * 180 / n)),
           cy + (ro if i % 2 == 0 else ri) * math.sin(math.radians(rot + i * 180 / n))) for i in range(2 * n)], **k)


def back():
    cx, cy = W / 2, H / 2
    P(f"M8,0H{W-8}A8,8 0 0,1 {W},8V{H-8}A8,8 0 0,1 {W-8},{H}H8A8,8 0 0,1 0,{H-8}V8A8,8 0 0,1 8,0Z", stroke=None, w=0, fill=BACK)
    P(f"M10,5H{W-10}A5,5 0 0,1 {W-5},10V{H-10}A5,5 0 0,1 {W-10},{H-5}H10A5,5 0 0,1 5,{H-10}V10A5,5 0 0,1 10,5Z", stroke=GOLD, w=0.8)
    P(f"M11,8H{W-11}A3,3 0 0,1 {W-8},11V{H-11}A3,3 0 0,1 {W-11},{H-8}H11A3,3 0 0,1 8,{H-11}V11A3,3 0 0,1 11,8Z", stroke=LAV, w=0.35, sa=0.6)
    # filigree corners
    for sx, sy in ((1, 1), (-1, 1), (1, -1), (-1, -1)):
        x0, y0 = (8 if sx > 0 else W - 8), (8 if sy > 0 else H - 8)
        P(f"M{f(x0)},{f(y0 + 16 * sy)}C{f(x0 + 4 * sx)},{f(y0 + 8 * sy)} {f(x0 + 8 * sx)},{f(y0 + 4 * sy)} {f(x0 + 16 * sx)},{f(y0)}", w=0.6)
        P(f"M{f(x0 + 6 * sx)},{f(y0 + 6 * sy)}m-1.6,0a1.6,1.6 0 1,0 3.2,0a1.6,1.6 0 1,0 -3.2,0", stroke=None, w=0, fill=GOLD)
    # star field
    import random
    rnd = random.Random(1909)
    for _ in range(70):
        x, y = rnd.uniform(12, W - 12), rnd.uniform(12, H - 12)
        if math.hypot(x - cx, y - cy) < 46: continue
        circle(x, y, rnd.uniform(0.25, 0.7), stroke=None, w=0, fill=MOON, fa=rnd.uniform(0.3, 0.85))
    # nakshatra ring: 27 beads, zodiac ring: 12 ticks
    circle(cx, cy, 44, stroke=OLD, w=0.6)
    circle(cx, cy, 39, stroke=GOLD, w=0.4, sa=0.7)
    for i in range(12):
        a = math.radians(i * 30)
        P(f"M{f(cx + 39 * math.cos(a))},{f(cy + 39 * math.sin(a))}L{f(cx + 44 * math.cos(a))},{f(cy + 44 * math.sin(a))}", w=0.5)
    for i in range(27):
        a = math.radians(i * 360 / 27 - 90)
        circle(cx + 41.5 * math.cos(a), cy + 41.5 * math.sin(a), 0.55, stroke=None, w=0, fill=LAV)
    # 16-petal lotus
    for i in range(16):
        a = i * 22.5
        r0, r1, wd = 22, 36, 5
        pts = []
        def rot(x, y):
            t = math.radians(a)
            return cx + x * math.cos(t) - y * math.sin(t), cy + x * math.sin(t) + y * math.cos(t)
        p0, c1, p1, c2 = rot(0, -r1), rot(wd, -(r0 + r1) / 2), rot(0, -r0), rot(-wd, -(r0 + r1) / 2)
        P(f"M{f(p0[0])},{f(p0[1])}Q{f(c1[0])},{f(c1[1])} {f(p1[0])},{f(p1[1])}Q{f(c2[0])},{f(c2[1])} {f(p0[0])},{f(p0[1])}Z", w=0.5, fill=GOLD, fa=0.08)
    circle(cx, cy, 22, stroke=GOLD, w=0.6)
    # yantra triangles
    for r, up in ((19, True), (19, False), (13, True), (13, False)):
        s = -1 if up else 1
        poly([(cx, cy + s * r), (cx + r * 0.866, cy - s * r / 2), (cx - r * 0.866, cy - s * r / 2)], stroke=GOLD if r > 15 else LAV, w=0.6)
    star(cx, cy, 4.2, 1.5, n=4, stroke=GOLD, w=0.4, fill=GOLD)
    # crescent and sun at top and bottom
    star(cx, 24, 4, 1.4, n=8, stroke=GOLD, w=0.4, fill=GOLD, fa=0.8)
    P(f"M{f(cx - 3)},{f(H - 28)}A5,5 0 1,0 {f(cx + 3.5)},{f(H - 20)}A4,4 0 1,1 {f(cx - 3)},{f(H - 28)}Z", stroke=None, w=0, fill=MOON)
    for y in (34, H - 34):
        P(f"M{f(cx - 26)},{y}H{f(cx - 7)}M{f(cx + 7)},{y}H{f(cx + 26)}", w=0.45, sa=0.8)


def to_vector():
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- ASTRA card back (original design) · generated by tools/tarot/make_classic.py, do not edit -->",
           f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{W}dp" android:height="{H}dp" android:viewportWidth="{W}" android:viewportHeight="{H}">']
    for d, stroke, w, fill, sa, fa in paths:
        a = [f'android:pathData="{d}"']
        if fill: a += [f'android:fillColor="{fill}"'] + ([f'android:fillAlpha="{fa:.2f}"'] if fa != 1 else [])
        if stroke: a += [f'android:strokeColor="{stroke}"', f'android:strokeWidth="{w}"', 'android:strokeLineCap="round"', 'android:strokeLineJoin="round"'] + ([f'android:strokeAlpha="{sa:.2f}"'] if sa != 1 else [])
        out.append("  <path " + " ".join(a) + "/>")
    return "\n".join(out + ["</vector>"]) + "\n"


def to_svg():
    body = "".join(f'<path d="{d}" fill="{fill or "none"}" fill-opacity="{fa}"' + (f' stroke="{s}" stroke-width="{w}" stroke-opacity="{sa}"' if s else "") + "/>"
                   for d, s, w, fill, sa, fa in paths)
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W * 3}" height="{H * 3}">{body}</svg>'


def main(src):
    res = os.path.join(ROOT, "app/src/main/res/drawable-nodpi")
    os.makedirs(res, exist_ok=True)
    total = 0
    for cid in IDS:
        im = Image.open(os.path.join(src, f"{cid}.jpg")).convert("RGB")
        im = im.resize((600, round(im.height * 600 / im.width)), Image.LANCZOS)
        out = os.path.join(res, f"tarot_{cid}.webp")
        im.save(out, "WEBP", quality=72, method=6)
        total += os.path.getsize(out)
    back()
    with open(os.path.join(ROOT, "app/src/main/res/drawable/tarot_back.xml"), "w") as fh: fh.write(to_vector())
    os.makedirs(os.path.join(ROOT, "build/tarot"), exist_ok=True)
    with open(os.path.join(ROOT, "build/tarot/back.svg"), "w") as fh: fh.write(to_svg())
    kt = os.path.join(ROOT, "app/src/main/java/app/astra/ui/tarot/TarotArt.kt")
    with open(kt, "w") as fh:
        fh.write("// Generated by tools/tarot/make_classic.py. Do not edit.\npackage app.astra.ui.tarot\n\nimport app.astra.R\n\n")
        fh.write("/** The classic tarot: Pamela Colman Smith, 1909 (public domain). Card back: ASTRA's own design. */\nobject TarotArt {\n")
        fh.write("    const val CREDIT = \"Classic tarot · Pamela Colman Smith, 1909 (public domain)\"\n    val BACK = R.drawable.tarot_back\n    /** Width / height of every card. */\n    const val ASPECT = 960f / 1670f\n\n")
        fh.write("    fun of(cardId: String): Int = when (cardId) {\n")
        for cid in IDS: fh.write(f'        "{cid}" -> R.drawable.tarot_{cid}\n')
        fh.write("        else -> R.drawable.tarot_back\n    }\n}\n")
    print(f"78 cards, {total / 1e6:.1f} MB")


if __name__ == "__main__":
    main(sys.argv[1])
